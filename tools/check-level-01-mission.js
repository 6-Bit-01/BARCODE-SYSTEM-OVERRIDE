#!/usr/bin/env node
const fs = require('fs');
const assert = require('assert');
const sector = fs.readFileSync('src/game/sector1-progression.js','utf8');
const jammer = fs.readFileSync('src/game/jammer-environment.js','utf8');
const combat = fs.readFileSync('src/game/player-combat.js','utf8');
const rhythm = fs.readFileSync('src/game/rhythm.js','utf8');
const enemies = fs.readFileSync('src/game/enemies.js','utf8');
const input = fs.readFileSync('src/core/input.js','utf8');
const gameState = fs.readFileSync('src/game/game-state.js','utf8');
const render = fs.readFileSync('src/game/render-coordinator.js','utf8');
const objectives = fs.readFileSync('src/game/objectives.js','utf8');
function must(text, re, msg) { assert(re.test(text), msg); }
const encounterBlocks = [...sector.matchAll(/\{ id: 'encounter_\d'[^]*?enemies: \[([^]*?)\] \}/g)];
assert.strictEqual(encounterBlocks.length, 4, 'four authored encounter definitions');
const counts = encounterBlocks.map(m => (m[1].match(/type: '/g) || []).length);
assert.strictEqual(counts.reduce((a,b)=>a+b,0), 20, 'exactly 20 quota enemies');
assert.deepStrictEqual(counts, [4,5,5,6], 'escalating readable encounter sizes');
must(sector, /STATES = Object\.freeze\(\{[^]*TUTORIAL: 'tutorial'[^]*BOSS_READY: 'boss_ready'/, 'explicit progression states through boss_ready');
must(sector, /shouldSuppressGenericSpawning\(\) \{ return true; \}/, 'generic endless spawning suppressed by mission owner');
must(sector, /startMission\(\)[^]*missionDefeats = 0[^]*enemyManagerReset/, 'tutorial completion resets mission counter and stale enemies');
must(sector, /_sector1MissionEnemy/, 'only mission enemies are marked for quota');
must(sector, /countedEnemies\.has\(enemy\)/, 'each enemy counts once');
must(sector, /missionDefeats === this\.requiredEnemyKills[^]*revealJammer/, 'jammer appears at exactly quota');
must(sector, /chooseJammerPosition\(\)[^]*px < WORLD_WIDTH \/ 2 \? 3520 : 620[^]*GROUND_Y/, 'jammer opposite safe ground');
must(sector, /FREEZE[^]*ENEMY_PURGE[^]*CAMERA_PAN[^]*BOSS_WALK_IN[^]*BOSS_FLOURISH[^]*BOSS_READY/, 'cinematic phase order is encoded');
must(sector, /freezeMs: 800/, 'named freeze duration');
must(sector, /panMs: 2000/, 'named pan duration');
must(sector, /purgeForCinematic/, 'enemy purge owner called');
must(sector, /t \* t \* \(3 - 2 \* t\)/, 'camera pan uses easing');
must(sector, /sector_1_boss_sector1boss[^]*sector_1_boss_walk_walk[^]*sector_1_boss_attack_attack[^]*sector_1_boss_idle_idle/s, 'approved boss sprite family used');
must(sector, /canDealDamage: false[^]*canReceiveDamage: false/s, 'boss cannot deal or receive damage');
must(sector, /bossReadyEmitted = true/, 'boss-ready handoff emitted');
must(sector, /reset\([^]*JammerEnvironment\.reset[^]*controlsDisabled = false/s, 'reset cleans cinematic/player/jammer state');
must(jammer, /health: 16[^]*maxHealth: 16/s, 'jammer starts with 16 health');
must(jammer, /targetable[^]*destroyed[^]*destructionNotified[^]*lastDamageSequence/s, 'authoritative jammer state fields');
must(jammer, /options\.timing === 'perfect' \|\| options\.timing === 'excellent'/, 'only perfect/excellent damage jammer');
must(jammer, /state\.health = Math\.max\(0, state\.health - 1\)/, 'successful attack deals exactly one jammer damage');
must(jammer, /lastDamageSequence === options\.sequence/, 'duplicate attack processing prevented');
must(jammer, /onJammerDestroyed/, 'jammer destruction notifies progression once');
must(combat, /tryDamageJammer\(player, judgment, result\.sequence\)/, 'PlayerCombat owns jammer attack transaction');
must(combat, /damage: 1/, 'jammer damage result is one point independent of enemy damage');
must(rhythm, /timing === 'miss'[^]*playSound\('synthHit', 0\.3\)/, 'exact miss plays synthHit once at 0.3');
must(enemies, /missionSuppressesGenericSpawning[^]*!missionSuppressesGenericSpawning/s, 'endless spawner cannot interfere');
must(enemies, /onEnemyDefeated\(this\.defeatedCount, enemy\)/, 'EnemyManager passes enemy identity for single counting');
must(enemies, /purgeForCinematic\(\)[^]*_purgedByCinematic[^]*_defeatRecorded = true[^]*this\.enemies = \[\]/s, 'purge removes active normal enemies without defeat credit callbacks');
must(input, /isGameplaySuppressed\(\)[^]*return false/, 'cinematic suppresses gameplay input');
must(gameState, /shouldSuppressGenericSpawning\(\)[^]*hasSpawnedInitialEnemies = true/s, 'initial generic post-tutorial spawn disabled');
must(render, /getCameraX\(cameraX\)/, 'render camera honors progression camera override');
must(objectives, /Defeat 20 enemies[^]*Successful rhythm attacks damage the Jammer[^]*Boss signal acquired/s, 'objectives cover mission, jammer, and boss-ready states');
must(input, /tutorialSystem\.handleSpacePress/, 'tutorial Space ownership preserved');
must(input, /actions\.jump\.pressed/, 'Up/jump action path preserved');
must(input, /resolvePrimary/, 'Down primary rhythm attack ownership preserved');
must(input, /hacking && typeof hacking\.start/, 'H hacking path preserved');
must(enemies, /Intentional passive landing stomp/, 'passive stomp remains lethal against normal enemies');
must(fs.readFileSync('src/engine/level-01-music-profile.js','utf8'), /LEVEL_01_MUSIC_PROFILE_ID = 'level-01\.main'/, 'Level 1 music profile remains explicit');
console.log('Level 1 mission static regression passed');
